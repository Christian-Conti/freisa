# Info     : Generates xheep_ooc_top.sv: a top with plain ports around X-HEEP's core_v_mini_mcu (whose CORE-V-XIF interface
#            ports cannot be top-level ports). Same ports minus the xif ones, type parameters replaced by their defaults,
#            numeric parameters kept as localparams, one if_xif instance on all xif ports (as in X-HEEP's testbench).
#            Run after `make mcu-gen` in X-HEEP: gen_ooc_top.py <path to generated core_v_mini_mcu.sv>
# Module   : gen_ooc_top.py
# Author   : Christian Conti
# Contact  : christian.conti@mail.it
import pathlib, re, sys

src = pathlib.Path(sys.argv[1]).read_text()
head = src[src.index("module core_v_mini_mcu"):]
params_txt = head[head.index("#(") + 2:head.index(") (")]
ports_txt = head[head.index(") (") + 3:head.index(");")]

types, localparams = {}, []
for line in params_txt.splitlines():
    line = re.sub(r"//.*", "", line).strip().rstrip(",")
    m = re.match(r"parameter\s+type\s+(\w+)\s*=\s*(\S+)", line)
    if m: types[m.group(1)] = m.group(2); continue
    m = re.match(r"parameter\s+(\w+)\s*=\s*(.+)", line)
    if m: localparams.append(f"  localparam {m.group(1)} = {m.group(2)};")

ports, xif = [], []
for line in ports_txt.splitlines():
    if "if_xif." in line:
        xif.append(re.search(r"(\w+)\s*,?\s*$", line.strip()).group(1)); continue
    for t, d in types.items(): line = re.sub(rf"\b{t}\b", d, line)
    ports.append(line)
ports = "\n".join(ports).rstrip().rstrip(",")

out = f"""// Generated by gen_ooc_top.py from X-HEEP's core_v_mini_mcu.sv: do not edit.
module xheep_ooc_top
  import core_v_mini_mcu_pkg::*;
({ports}
);
{chr(10).join(localparams)}
  if_xif ext_if ();  // CORE-V-XIF unused, as in X-HEEP's testbench
  core_v_mini_mcu u_mcu (
      .*,
{(","+chr(10)).join(f"      .{x}(ext_if)" for x in xif)}
  );
endmodule
"""
(pathlib.Path(__file__).parent / "xheep_ooc_top.sv").write_text(out)
print(f"xheep_ooc_top.sv: {len(xif)} xif ports tied to one if_xif, {len(localparams)} localparams, {len(types)} types")
